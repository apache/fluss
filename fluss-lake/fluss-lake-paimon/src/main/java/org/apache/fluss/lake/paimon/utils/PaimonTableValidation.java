package org.apache.fluss.lake.paimon.utils;

import org.apache.fluss.exception.TableAlreadyExistException;
import org.apache.fluss.metadata.TablePath;

import org.apache.paimon.CoreOptions;
import org.apache.paimon.schema.Schema;
import org.apache.paimon.table.FileStoreTable;
import org.apache.paimon.types.DataField;
import org.apache.paimon.types.DataTypes;
import org.apache.paimon.types.RowType;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Objects;

import static org.apache.fluss.lake.paimon.PaimonLakeCatalog.LEGACY_SYSTEM_COLUMNS;
import static org.apache.fluss.lake.paimon.utils.PaimonConversions.PAIMON_UNSETTABLE_OPTIONS;
import static org.apache.fluss.lake.paimon.utils.PaimonConversions.PARTITION_GENERATE_LEGACY_NAME_OPTION_KEY;
import static org.apache.fluss.metadata.TableDescriptor.TIMESTAMP_COLUMN_NAME;

/** Utils to verify whether the existing Paimon table is compatible with the table to be created. */
public class PaimonTableValidation {

    public static boolean isPaimonSchemaCompatible(Schema existingSchema, Schema newSchema) {
        // FIP-27: newly generated schemas are always clean (no system columns). When the existing
        // table is a legacy table that still carries the three system columns (recognisable by the
        // presence of the __timestamp column), re-enabling lake tiering must keep that physical
        // layout. Enrich the clean new schema with the trailing system columns before comparison,
        // so an existing legacy table is recognised as compatible and its layout is preserved.
        if (PaimonUtils.isLegacyTable(existingSchema.rowType())) {
            newSchema = appendSystemColumns(newSchema);
        }

        if (!equalPhysicalSchema(existingSchema, newSchema)) {
            // Allow different precisions for __timestamp column for backward compatibility,
            // old cluster will use precision 6, but new cluster will use precision 3,
            // we allow such precision difference
            return equalIgnoreSystemColumnTimestampPrecision(existingSchema, newSchema);
        }

        return true;
    }

    /**
     * Returns a copy of {@code cleanSchema} with the three Fluss system columns appended as the
     * last physical columns, so a clean schema generated by the current cluster can be compared
     * against an existing legacy table. Partition keys, primary keys, options and comment are
     * preserved. System-column field ids continue the existing id sequence to avoid collisions;
     * they are irrelevant to {@link #equalPhysicalSchema}, which ignores field ids.
     */
    private static Schema appendSystemColumns(Schema cleanSchema) {
        List<DataField> fields = new ArrayList<>(cleanSchema.fields());
        int nextFieldId = 0;
        for (DataField field : fields) {
            nextFieldId = Math.max(nextFieldId, field.id() + 1);
        }
        for (Map.Entry<String, org.apache.paimon.types.DataType> systemColumn :
                LEGACY_SYSTEM_COLUMNS.entrySet()) {
            fields.add(
                    new DataField(nextFieldId++, systemColumn.getKey(), systemColumn.getValue()));
        }
        return new Schema(
                fields,
                cleanSchema.partitionKeys(),
                cleanSchema.primaryKeys(),
                cleanSchema.options(),
                cleanSchema.comment());
    }

    /**
     * Check if the {@code existingSchema} is compatible with {@code newSchema} by ignoring the
     * precision difference of the system column {@code __timestamp}.
     *
     * <p>This is crucial for backward compatibility during cluster upgrades or configuration
     * changes (e.g., transitioning from precision 6 to 3). Without this relaxed check, users would
     * be unable to re-enable lake synchronization for existing tables if the cluster-wide default
     * timestamp precision has evolved.
     *
     * @param existingSchema the schema currently persisted in the Paimon catalog
     * @param newSchema the new schema descriptor generated by the current Fluss cluster
     * @return true if the physical schemas are identical, disregarding field IDs, comments, regular
     *     options, and the precision of the system timestamp
     */
    public static boolean equalIgnoreSystemColumnTimestampPrecision(
            Schema existingSchema, Schema newSchema) {
        List<DataField> existingFields = new ArrayList<>(existingSchema.fields());
        // The precision relaxation only applies to a legacy table's trailing __timestamp system
        // column. A clean table (or any table whose last column is not __timestamp) has no such
        // column, so there is nothing to relax and we compare the schemas directly.
        if (existingFields.isEmpty()
                || !existingFields
                        .get(existingFields.size() - 1)
                        .name()
                        .equals(TIMESTAMP_COLUMN_NAME)) {
            return equalPhysicalSchema(existingSchema, newSchema);
        }
        DataField systemTimestampField = existingFields.get(existingFields.size() - 1);
        if (systemTimestampField.name().equals(TIMESTAMP_COLUMN_NAME)
                && systemTimestampField
                        .type()
                        .equalsIgnoreFieldId(DataTypes.TIMESTAMP_WITH_LOCAL_TIME_ZONE())) {
            existingFields.set(
                    existingFields.size() - 1,
                    new DataField(
                            systemTimestampField.id(),
                            systemTimestampField.name(),
                            DataTypes.TIMESTAMP_LTZ_MILLIS(),
                            systemTimestampField.description()));
        }
        existingSchema = existingSchema.copy(RowType.of(existingFields.toArray(new DataField[0])));
        return equalPhysicalSchema(existingSchema, newSchema);
    }

    private static boolean equalPhysicalSchema(Schema existingSchema, Schema newSchema) {
        List<DataField> existingFields = existingSchema.fields();
        List<DataField> newFields = newSchema.fields();
        if (existingFields.size() != newFields.size()) {
            return false;
        }

        for (int i = 0; i < existingFields.size(); i++) {
            DataField existingField = existingFields.get(i);
            DataField newField = newFields.get(i);
            if (!equalDataFieldIgnoreFieldId(existingField, newField)) {
                return false;
            }
        }

        return Objects.equals(existingSchema.partitionKeys(), newSchema.partitionKeys())
                && Objects.equals(existingSchema.primaryKeys(), newSchema.primaryKeys())
                && equalPaimonOptions(existingSchema.options(), newSchema.options());
    }

    private static boolean equalPaimonOptions(
            Map<String, String> existingOptions, Map<String, String> newOptions) {
        if (!Objects.equals(
                existingOptions.get(PARTITION_GENERATE_LEGACY_NAME_OPTION_KEY),
                Boolean.FALSE.toString())) {
            return false;
        }

        for (String option : PAIMON_UNSETTABLE_OPTIONS) {
            if (!Objects.equals(existingOptions.get(option), newOptions.get(option))) {
                return false;
            }
        }

        for (String option : CoreOptions.IMMUTABLE_OPTIONS) {
            if (!Objects.equals(existingOptions.get(option), newOptions.get(option))) {
                return false;
            }
        }

        return true;
    }

    private static boolean equalDataFieldIgnoreFieldId(
            DataField existingField, DataField newField) {
        return Objects.equals(existingField.name(), newField.name())
                && existingField.type().equalsIgnoreFieldId(newField.type());
    }

    public static void checkTableIsEmpty(TablePath tablePath, FileStoreTable table) {
        if (table.latestSnapshot().isPresent()) {
            throw new TableAlreadyExistException(
                    String.format(
                            "The table %s already exists in Paimon catalog, and the table is not empty. "
                                    + "Please first drop the table in Paimon catalog or use a new table name.",
                            tablePath));
        }
    }
}
