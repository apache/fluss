    #[derive(Debug, Deserialize, PartialEq)]
    #[serde(deny_unknown_fields)]
    struct BodyFixture {
        value: u32,
    }

    async fn body_json(response: Response) -> serde_json::Value {
        let bytes = response
            .into_body()
            .collect()
            .await
            .expect("body")
            .to_bytes();
        serde_json::from_slice(&bytes).expect("json body")
    }

    #[tokio::test]
    async fn shared_json_parser_enforces_media_type_and_serde_strictness() {
        for (content_type, expected) in [
            (None, Err(ErrorKind::UnsupportedMediaType)),
            (Some("text/plain"), Err(ErrorKind::UnsupportedMediaType)),
            (Some("application/json"), Ok(BodyFixture { value: 7 })),
            (
                Some("application/vnd.fluss+json; charset=utf-8"),
                Ok(BodyFixture { value: 7 }),
            ),
        ] {
            let mut request = Request::builder();
            if let Some(content_type) = content_type {
                request = request.header(header::CONTENT_TYPE, content_type);
            }
            let request = request.body(Body::from(r#"{"value": 7}"#)).unwrap();
            let result = parse_json_body::<BodyFixture>(request)
                .await
                .map_err(|error| error.kind());
            assert_eq!(result, expected, "{content_type:?}");
        }
        for body in [
            r#"{"value": 7, "unknown": true}"#,
            r#"{"value": 7, "value": 8}"#,
            r#"{"value":"#,
            "",
        ] {
            let request = Request::builder()
                .header(header::CONTENT_TYPE, "application/json")
                .body(Body::from(body))
                .unwrap();
            let error = parse_json_body::<BodyFixture>(request).await.unwrap_err();
            assert_eq!(error.kind(), ErrorKind::InvalidArgument, "{body}");
        }

        let stream =
            futures_util::stream::iter([Err::<Bytes, _>(std::io::Error::other("read failed"))]);
        let error = parse_json_body::<BodyFixture>(Request::new(Body::from_stream(stream)))
            .await
            .unwrap_err();
        assert_eq!(error.kind(), ErrorKind::InvalidArgument);
        assert!(error.message().starts_with("unreadable request body:"));
    }

    #[tokio::test]
    async fn unknown_route_yields_404_envelope() {
        let app = build_router(test_support::test_state(), &test_support::test_options());
        for path in ["/nope", "/nope?unknown=value"] {
            let response = app
                .clone()
                .oneshot(Request::builder().uri(path).body(Body::empty()).unwrap())
                .await
                .unwrap();

            assert_eq!(response.status(), StatusCode::NOT_FOUND, "{path}");
            let header_id = response
                .headers()
                .get("x-request-id")
                .and_then(|v| v.to_str().ok())
                .map(str::to_string)
                .expect("x-request-id header");

            let json = body_json(response).await;
            assert_eq!(json["error"]["code"], "not_found", "{path}");
            assert_eq!(json["error"]["request_id"], header_id.as_str(), "{path}");
            assert!(
                json["error"]["message"].as_str().unwrap().contains("/nope"),
                "message names the missing route: {json}"
            );
        }
    }

    #[tokio::test]
    async fn oversized_body_yields_413_envelope() {
        let state = test_support::test_state();
        state.readiness.set_serving();
        let app = build_router(state, &test_support::test_options());
        for (method, path) in [
            (Method::POST, "/v1/clusters/default/databases"),
            (
                Method::GET,
                "/v1/clusters/default/databases/sales/tables/orders",
            ),
            (
                Method::DELETE,
                "/v1/clusters/default/databases/sales/tables/orders",
            ),
        ] {
            let response = app
                .clone()
                .oneshot(
                    Request::builder()
                        .method(method.clone())
                        .uri(path)
                        .header(header::CONTENT_LENGTH, "1048576")
                        .body(Body::empty())
                        .unwrap(),
                )
                .await
                .unwrap();

            assert_eq!(response.status(), StatusCode::PAYLOAD_TOO_LARGE, "{method}");
            let json = body_json(response).await;
            assert_eq!(json["error"]["code"], "limit_exceeded", "{method}");
            assert!(json["error"]["request_id"].as_str().is_some(), "{method}");
        }
    }

    #[tokio::test]
    async fn request_timeout_yields_504_envelope() {
        /// Runs longer than the configured test request deadline.
        async fn slow() -> &'static str {
            tokio::time::sleep(Duration::from_millis(250)).await;
            "ok"
        }
        let mut options = test_support::test_options();
        options.request_timeout = Duration::from_millis(50);
        let app = apply_middleware(Router::new().route("/slow", get(slow)), &options);

        let response = app
            .oneshot(Request::builder().uri("/slow").body(Body::empty()).unwrap())
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::GATEWAY_TIMEOUT);
        let json = body_json(response).await;
        assert_eq!(json["error"]["code"], "timeout");
    }

    /// The deadline reserves the response grace, except for timeouts that are not longer than it,
    /// which keep their full budget.
    #[test]
    fn the_deadline_reserves_the_response_grace_when_the_timeout_allows_it() {
        for (timeout, budget) in [
            (
                Duration::from_secs(30),
                Duration::from_secs(30) - REST_RESPONSE_GRACE,
            ),
            (REST_RESPONSE_GRACE, REST_RESPONSE_GRACE),
            (Duration::from_millis(200), Duration::from_millis(200)),
        ] {
            let before = Instant::now();
            let deadline = deadline_from_now(timeout).instant();
            let after = Instant::now();

            assert!(deadline >= before + budget, "timeout={timeout:?}");
            assert!(
                deadline <= after + budget + Duration::from_millis(50),
                "timeout={timeout:?}"
            );
        }
    }

    /// A handler that finishes exactly at its deadline still gets its response out: the middleware
    /// timeout backstops the deadline plus the response grace instead of racing it.
    #[tokio::test]
    async fn response_completing_at_the_deadline_is_delivered() {
        async fn finishes_at_deadline(request: Request) -> &'static str {
            let deadline = request
                .extensions()
                .get::<RequestDeadline>()
                .copied()
                .expect("the limits middleware assigns the deadline");
            tokio::time::sleep_until(tokio::time::Instant::from_std(deadline.instant())).await;
            "ok"
        }
        let mut options = test_support::test_options();
        options.request_timeout = REST_RESPONSE_GRACE + Duration::from_millis(400);
        let app = apply_middleware(
            Router::new().route("/deadline", get(finishes_at_deadline)),
            &options,
        );

        let response = app
            .oneshot(
                Request::builder()
                    .uri("/deadline")
                    .body(Body::empty())
                    .unwrap(),
            )
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::OK);
    }

