    #[tokio::test]
    async fn generic_middleware_does_not_impose_a_global_concurrency_limit() {
        /// Holds a request open long enough for several to overlap.
        async fn slow() -> &'static str {
            tokio::time::sleep(Duration::from_millis(50)).await;
            "ok"
        }
        let app = apply_middleware(
            Router::new().route("/slow", get(slow)),
            &test_support::test_options(),
        );
        let request = || Request::builder().uri("/slow").body(Body::empty()).unwrap();

        let responses =
            futures_util::future::join_all((0..16).map(|_| app.clone().oneshot(request()))).await;

        for response in responses {
            assert_eq!(response.unwrap().status(), StatusCode::OK);
        }
    }

    #[tokio::test]
    async fn metadata_concurrency_rejects_without_queueing_and_releases_its_permit() {
        let entered = Arc::new(tokio::sync::Notify::new());
        let release = Arc::new(tokio::sync::Notify::new());
        let calls = Arc::new(AtomicUsize::new(0));
        let handler = {
            let entered = entered.clone();
            let release = release.clone();
            let calls = calls.clone();
            move || {
                let entered = entered.clone();
                let release = release.clone();
                let calls = calls.clone();
                async move {
                    if calls.fetch_add(1, Ordering::SeqCst) == 0 {
                        entered.notify_one();
                        release.notified().await;
                    }
                    "ok"
                }
            }
        };
        let app = apply_common_middleware(
            apply_concurrency_limit(
                Router::new().route("/metadata", get(handler)),
                1,
                "too many concurrent metadata requests",
            ),
            None,
        );
        let request = || {
            Request::builder()
                .uri("/metadata")
                .body(Body::empty())
                .unwrap()
        };

        let first = tokio::spawn(app.clone().oneshot(request()));
        entered.notified().await;

        let rejected = app.clone().oneshot(request()).await.unwrap();
        assert_eq!(rejected.status(), StatusCode::TOO_MANY_REQUESTS);
        assert_eq!(rejected.headers()[header::RETRY_AFTER], "1");
        assert_eq!(
            body_json(rejected).await["error"]["code"],
            "resource_exhausted"
        );
        assert_eq!(calls.load(Ordering::SeqCst), 1);

        release.notify_one();
        assert_eq!(first.await.unwrap().unwrap().status(), StatusCode::OK);
        assert_eq!(
            app.oneshot(request()).await.unwrap().status(),
            StatusCode::OK
        );
        assert_eq!(calls.load(Ordering::SeqCst), 2);
    }

